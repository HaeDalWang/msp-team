export function koreanPublicHolidays(year) {
  const dates = new Map(fixedHolidays.map(([monthDay, name]) => [`${year}-${monthDay}`, name]))
  for (const [monthDay, name] of variableHolidays[year] ?? []) dates.set(`${year}-${monthDay}`, name)
  return dates
}
